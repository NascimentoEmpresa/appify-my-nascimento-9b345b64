-- ── 4) Tabelas ───────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public."PONTO_ENVIO_ENCARREGADO" (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mes_referencia    text   NOT NULL CHECK (mes_referencia ~ '^\d{4}-\d{2}$'),
  contrato_empresa  bigint NOT NULL,
  contrato_filial   bigint NOT NULL,
  contrato_nome     text,
  posto             text   NOT NULL DEFAULT '',   -- recorte opcional ('' = contrato todo)
  encarregado_id    uuid   NOT NULL DEFAULT auth.uid(),
  encarregado_nome  text,
  status            text   NOT NULL DEFAULT 'rascunho'
                      CHECK (status IN ('rascunho', 'enviado', 'devolvido', 'recebido')),
  observacao        text,
  enviado_em        timestamptz,
  recebido_por      text, recebido_em timestamptz,
  devolvido_por     text, devolvido_em timestamptz, devolucao_motivo text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now(),
  -- Um envio por encarregado, contrato, posto e mês (posto '' = contrato todo).
  CONSTRAINT pee_unico UNIQUE (mes_referencia, contrato_empresa, contrato_filial, encarregado_id, posto)
);
CREATE INDEX IF NOT EXISTS idx_pee_mes_contrato ON public."PONTO_ENVIO_ENCARREGADO"(mes_referencia, contrato_empresa, contrato_filial);
CREATE INDEX IF NOT EXISTS idx_pee_encarregado ON public."PONTO_ENVIO_ENCARREGADO"(encarregado_id);

DROP TRIGGER IF EXISTS trg_pee_updated ON public."PONTO_ENVIO_ENCARREGADO";
CREATE TRIGGER trg_pee_updated BEFORE UPDATE ON public."PONTO_ENVIO_ENCARREGADO"
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE IF NOT EXISTS public."PONTO_ENVIO_ITEM" (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  envio_id       bigint NOT NULL REFERENCES public."PONTO_ENVIO_ENCARREGADO"(id) ON DELETE CASCADE,
  empregado_id   bigint,
  nome           text NOT NULL,
  cadastro       bigint,
  cargo          text,
  posto          text,
  situacao       text NOT NULL DEFAULT 'ok'
                   CHECK (situacao IN ('ok', 'faltas', 'atestado', 'ferias', 'afastado', 'desligado', 'divergencia')),
  faltas         integer NOT NULL DEFAULT 0 CHECK (faltas >= 0),
  atrasos        integer NOT NULL DEFAULT 0 CHECK (atrasos >= 0),
  horas_extras   text,
  dias_marcados  integer,             -- foto do relógio no envio
  dias_sem_marcacao integer,
  observacao     text,
  CONSTRAINT pei_unico UNIQUE (envio_id, empregado_id)
);
CREATE INDEX IF NOT EXISTS idx_pei_envio ON public."PONTO_ENVIO_ITEM"(envio_id);

CREATE TABLE IF NOT EXISTS public."PONTO_ENVIO_ANEXO" (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  envio_id      bigint NOT NULL REFERENCES public."PONTO_ENVIO_ENCARREGADO"(id) ON DELETE CASCADE,
  storage_path  text NOT NULL,
  nome_arquivo  text,
  mime_type     text,
  tamanho_bytes bigint,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_pea_envio ON public."PONTO_ENVIO_ANEXO"(envio_id);

CREATE TABLE IF NOT EXISTS public."PONTO_ENVIO_EVENTO" (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  envio_id    bigint NOT NULL REFERENCES public."PONTO_ENVIO_ENCARREGADO"(id) ON DELETE CASCADE,
  acao        text NOT NULL,          -- criado | salvo | enviado | recebido | devolvido
  de_status   text,
  para_status text,
  observacao  text,
  autor_id    uuid DEFAULT auth.uid(),
  autor_nome  text,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_pev_envio ON public."PONTO_ENVIO_EVENTO"(envio_id, created_at);

