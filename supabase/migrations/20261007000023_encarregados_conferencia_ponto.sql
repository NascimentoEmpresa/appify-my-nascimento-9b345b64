CREATE OR REPLACE FUNCTION public.ponto_enc_pode_ver(_envio bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT EXISTS (
    SELECT 1 FROM public."PONTO_ENVIO_ENCARREGADO" e
     WHERE e.id = _envio
       AND ((e.encarregado_id = auth.uid() AND public.ponto_enc_eh_encarregado())
            OR (e.status <> 'rascunho' AND public.ponto_enc_eh_operacional())))
$$;
