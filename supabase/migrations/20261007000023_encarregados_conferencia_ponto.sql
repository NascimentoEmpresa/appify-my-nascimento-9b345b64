-- operacional no começo da folha de pagamento. A etapa iniciava no
-- operacional antes, mas agora vai iniciar no encarregados. Deixa todos sem
-- permissão por enquanto, ainda vamos modificar bastante coisa."
--
-- O FLUXO (a Conferência de Ponto ganha uma casa ANTES do Operacional):
--
--   Encarregado monta o ENVIO do mês para o contrato (Empresa, Filial):
--     · a lista dos colaboradores do contrato, cada um com a situação do mês
--       (ok, faltas, atestado, férias, afastado, desligado, divergência),
--       faltas/atrasos/horas extras e observação — a tela já traz o que o
--       relógio (espelho."BiMarcacoes") registrou: dias com batida e dias
--       úteis sem batida, para ele conferir antes de mandar;
--     · os arquivos das folhas/espelhos de ponto (obrigatório ≥ 1).
--   Enviar → o envio fica "enviado" e a linha do contrato na Conferência de
--   Ponto (SISTEMA_CONFERENCIA_PONTO) passa de "Pendente Encarregados" para
--   "Pendente Operacional" (ou nasce assim).
--   O Operacional RECEBE (ok) ou DEVOLVE com motivo — o encarregado recebe a
--   notificação, corrige e reenvia.
--
-- STATUS NOVO "Pendente Encarregados": é o status de quem ainda não tem
-- envio. O Operacional CONTINUA podendo conferir/aprovar a partir dele —
-- enquanto ninguém tem a tela dos encarregados liberada, o fluxo de hoje
-- não pode travar.
--
-- PERMISSÕES — nenhuma concedida (pedido explícito). Menus criados:
--   encarregados_conferencia_ponto  (tela, módulo Encarregados)
--   ponto_receber_encarregados      (fantasma, Operacional: receber/devolver)
-- Liberar em Administração › Acesso por Usuário quando for a hora.
--
-- Idempotente. Aplicar no banco do app — não se auto-aplica. Depende da
-- 20261007000021 (diaria_ponto_sincronizado_ate) para o "relógio até".
-- =========================================================================

