-- 3) Reconstrução do vínculo --------------------------------------------------
--
-- O nome do contrato no sistema antigo era string digitada ('UFRGS-LIMPEZA
-- GERAL- 047 2022' x 'UFRGS - LIMPEZA GERAL - 047/2022'), então o casamento
-- ignora acento e tudo que não é letra ou dígito. Nome que casa com MAIS DE UM
-- contrato fica de fora: ambiguidade não vira chute.

WITH contrato_chave AS (
  SELECT c.id,
         regexp_replace(
           upper(translate(c.nome,
             'ÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇáàâãäéèêëíìîïóòôõöúùûüç',
             'AAAAAEEEEIIIIOOOOOUUUUCAAAAAEEEEIIIIOOOOOUUUUC')),
           '[^A-Z0-9]', '', 'g') AS chave
    FROM public.contratos c
),
-- Chave que aponta para mais de um contrato (existe uma: UFSM MOTORISTAS
-- 099/2026, duplicada no cadastro) é descartada aqui pelo HAVING.
contrato_unico AS (
  SELECT chave, (array_agg(id))[1] AS contrato_id
    FROM contrato_chave
   GROUP BY chave
  HAVING count(*) = 1
),
alvo AS (
  SELECT d.protocolo, d.fonte, u.contrato_id
    FROM tmp_depara_0769 d
    JOIN contrato_unico u
      ON u.chave = regexp_replace(
           upper(translate(d.contrato_nome,
             'ÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇáàâãäéèêëíìîïóòôõöúùûüç',
             'AAAAAEEEEIIIIOOOOOUUUUCAAAAAEEEEIIIIOOOOOUUUUC')),
           '[^A-Z0-9]', '', 'g')
)
UPDATE public.sup_estoque_consumo c
   SET contrato_id_reconstruido = a.contrato_id,
       contrato_origem          = a.fonte
  FROM alvo a
 WHERE c.pedido_id_legado = a.protocolo
   AND c.pedido_id IS NULL;         -- nunca sobrescreve vínculo real

-- Índice só sobre as linhas reconstruídas: são ~2,5 mil numa tabela de 8 mil,
-- e o relatório filtra por elas.
CREATE INDEX IF NOT EXISTS idx_sup_consumo_contrato_reconstruido
  ON public.sup_estoque_consumo(contrato_id_reconstruido)
  WHERE contrato_id_reconstruido IS NOT NULL;

-- 4) RPC do relatório ---------------------------------------------------------
--
-- Fonte é sup_estoque_consumo, NÃO sup_estoque_movimento: a trilha de
-- movimento só existe a partir de setembro/2026 e devolve zero para o período
-- que o chamado pede — foi esse zero que apareceu na tela e gerou o chamado.
--
-- Devolve a linha "sem contrato identificado" (contrato_id NULL) em vez de
-- descartá-la: esconder as 734 unidades sem destino entregaria um número que
-- fecha e mente.

CREATE OR REPLACE FUNCTION public.sup_rel_saidas_por_contrato(
  p_inicio      date,
  p_fim         date,
  p_contrato_id uuid DEFAULT NULL
)
RETURNS TABLE (
  competencia    text,
  contrato_id    uuid,
  contrato_nome  text,
  sup_item_id    uuid,
  item_nome      text,
  item_codigo    text,
  item_tipo      text,
  quantidade     bigint,
  origem         text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT to_char(c.consumido_em, 'YYYY-MM')                      AS competencia,
         COALESCE(p.contrato_id, c.contrato_id_reconstruido)      AS contrato_id,
         COALESCE(p.contrato_nome, ct.nome, '(sem contrato identificado)') AS contrato_nome,
         i.id                                                     AS sup_item_id,
         COALESCE(i.nome, '(material removido)')                  AS item_nome,
         i.codigo                                                 AS item_codigo,
         i.tipo                                                   AS item_tipo,
         sum(c.quantidade)::bigint                                AS quantidade,
         CASE
           WHEN p.id IS NOT NULL                       THEN 'sistema'
           WHEN c.contrato_id_reconstruido IS NOT NULL THEN 'planilha:' || COALESCE(c.contrato_origem, '?')
           ELSE 'sem_destino'
         END                                                      AS origem
    FROM public.sup_estoque_consumo c
    LEFT JOIN public.sup_pedido        p  ON p.id  = c.pedido_id
    LEFT JOIN public.contratos         ct ON ct.id = c.contrato_id_reconstruido
    LEFT JOIN public.sup_estoque_item  ei ON ei.id = c.item_estoque_id
    LEFT JOIN public.sup_item          i  ON i.id  = ei.sup_item_id
   WHERE public.has_screen_access(auth.uid(), 'sup_rel_saidas_contrato', 'visualizar')
     AND c.consumido_em >= p_inicio::timestamptz
     AND c.consumido_em <  (p_fim + 1)::timestamptz
     AND (p_contrato_id IS NULL
          OR COALESCE(p.contrato_id, c.contrato_id_reconstruido) = p_contrato_id)
   GROUP BY 1, 2, 3, 4, 5, 6, 7, 9
   ORDER BY 1, 3, 5;
$$;

REVOKE ALL ON FUNCTION public.sup_rel_saidas_por_contrato(date, date, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.sup_rel_saidas_por_contrato(date, date, uuid) TO authenticated;

-- Cobertura do período: é o aviso que a tela mostra no topo, para ninguém ler
-- abril/2026 como se fosse um mês íntegro.
CREATE OR REPLACE FUNCTION public.sup_rel_saidas_cobertura(
  p_inicio date,
  p_fim    date
)
RETURNS TABLE (
  competencia      text,
  unidades_total   bigint,
  unidades_sistema bigint,
  unidades_planilha bigint,
  unidades_sem_destino bigint
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT to_char(c.consumido_em, 'YYYY-MM') AS competencia,
         sum(c.quantidade)::bigint,
         sum(c.quantidade) FILTER (WHERE c.pedido_id IS NOT NULL)::bigint,
         sum(c.quantidade) FILTER (WHERE c.pedido_id IS NULL
                                     AND c.contrato_id_reconstruido IS NOT NULL)::bigint,
         sum(c.quantidade) FILTER (WHERE c.pedido_id IS NULL
                                     AND c.contrato_id_reconstruido IS NULL)::bigint
    FROM public.sup_estoque_consumo c
   WHERE public.has_screen_access(auth.uid(), 'sup_rel_saidas_contrato', 'visualizar')
     AND c.consumido_em >= p_inicio::timestamptz
     AND c.consumido_em <  (p_fim + 1)::timestamptz
   GROUP BY 1
   ORDER BY 1;
$$;

REVOKE ALL ON FUNCTION public.sup_rel_saidas_cobertura(date, date) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.sup_rel_saidas_cobertura(date, date) TO authenticated;

