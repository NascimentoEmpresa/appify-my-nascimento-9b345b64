-- p_postos: [{ "posto": "...", "implantado": 8, "justificativa": "..." }, ...]
-- Grava uma linha por posto enviado (mesmo sem mudança: é a confirmação do
-- ciclo). Tudo ou nada.
CREATE OR REPLACE FUNCTION public.contrato_implantacao_salvar(p_contrato_id uuid, p_vale_a_partir_de date, p_postos jsonb)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp
AS $fn$
DECLARE
  v_uid  uuid := auth.uid();
  v_nome text;
  v_item jsonb;
  v_base record;
  v_impl integer;
  v_just text;
  v_n    integer := 0;
BEGIN
  IF NOT public.has_screen_access(v_uid, 'licitacoes_contratos_implantacao', 'alterar') THEN
    RAISE EXCEPTION 'Sem permissão para registrar a implantação de postos.' USING ERRCODE = '42501';
  END IF;
  IF p_vale_a_partir_de IS NULL THEN
    RAISE EXCEPTION 'Informe a partir de quando vale.';
  END IF;
  IF jsonb_typeof(p_postos) IS DISTINCT FROM 'array' OR jsonb_array_length(p_postos) = 0 THEN
    RAISE EXCEPTION 'Nenhum posto enviado.';
  END IF;

  SELECT COALESCE(NULLIF(btrim(p.display_name), ''), u.email) INTO v_nome
    FROM auth.users u LEFT JOIN public.profiles p ON p.id = u.id
   WHERE u.id = v_uid;

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_postos) LOOP
    SELECT * INTO v_base
      FROM public.contrato_postos_base(current_date) b
     WHERE b.contrato_id = p_contrato_id AND b.posto_norm = public.sup_norm_nome(v_item->>'posto') AND NOT b.rt;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'O posto "%" não está na Planilha de Custo vigente deste contrato.', v_item->>'posto';
    END IF;

    v_impl := NULLIF(v_item->>'implantado', '')::integer;
    IF v_impl IS NULL OR v_impl < 0 THEN
      RAISE EXCEPTION 'Implantado inválido no posto "%".', v_base.posto;
    END IF;
    v_just := NULLIF(btrim(COALESCE(v_item->>'justificativa', '')), '');
    IF v_impl <> v_base.previsto AND length(COALESCE(v_just, '')) < 5 THEN
      RAISE EXCEPTION 'Justifique por que o posto "%" tem % implantado(s) e % previsto(s).', v_base.posto, v_impl, v_base.previsto;
    END IF;

    INSERT INTO public."CONTRATO_POSTO_IMPLANTADO"
      (contrato_id, posto, posto_norm, previsto_no_registro, implantado, vale_a_partir_de,
       justificativa, registrado_por, registrado_por_nome)
    VALUES
      (p_contrato_id, v_base.posto, v_base.posto_norm, v_base.previsto, v_impl, p_vale_a_partir_de,
       v_just, v_uid, v_nome);
    v_n := v_n + 1;
  END LOOP;

  RETURN v_n;
END $fn$;
REVOKE ALL ON FUNCTION public.contrato_implantacao_salvar(uuid, date, jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.contrato_implantacao_salvar(uuid, date, jsonb) TO authenticated;

-- ── 5. RH › Ativos/Contratos: postos com previsto e implantado ──────────
-- Corpo igual ao da mig 20261020000090, com duas diferenças: pv sai da
-- conta única, e cada posto leva 'implantado' (+ 'previsto' e
-- 'implantado_registrado'). 'vagas' segue sendo o previsto — front antigo
-- continua igual até publicar.
CREATE OR REPLACE FUNCTION public.rh_ac_painel()
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp
AS $$
DECLARE v_out jsonb;
BEGIN
  PERFORM public.rh_ac_exige();

  WITH pessoas AS MATERIALIZED (SELECT * FROM public.rh_ac_ativos()),
  pv AS MATERIALIZED (
    SELECT b.contrato_id, b.posto, b.posto_norm AS pn, b.previsto AS vagas, b.implantado, b.registrado
      FROM public.contrato_postos_base(current_date) b
  ),
  -- Posto da Senior → UM posto da planilha (ou fora da conta).
  lig AS MATERIALIZED (
    SELECT DISTINCT ON (d.contrato_id, d.posto_senior)
           d.contrato_id, d.posto_senior, d.ignorar, pv.posto AS planilha_posto
      FROM public."RH_POSTO_DEPARA" d
      LEFT JOIN pv ON pv.contrato_id = d.contrato_id
                  AND pv.pn = public.sup_norm_nome(d.planilha_posto)
     WHERE d.ignorar OR pv.posto IS NOT NULL
     ORDER BY d.contrato_id, d.posto_senior, d.ignorar DESC, pv.posto
  ),
  pes AS MATERIALIZED (
    SELECT p.*,
           CASE WHEN oc.planilha_posto = '' THEN NULL
                WHEN oc.rt THEN 'RENDA TÉCNICA'
                WHEN pvo.posto IS NOT NULL THEN pvo.posto
                WHEN l.ignorar THEN NULL
                ELSE l.planilha_posto END AS posto,
           (oc.planilha_posto = '' OR (NOT COALESCE(oc.rt, false) AND pvo.posto IS NULL AND COALESCE(l.ignorar, false))) IS TRUE AS fora,
           CASE WHEN oc.planilha_posto = '' OR oc.rt OR pvo.posto IS NOT NULL THEN 'pessoa'
                WHEN l.ignorar OR l.planilha_posto IS NOT NULL THEN 'posto' END AS origem
      FROM pessoas p
      LEFT JOIN LATERAL (
        SELECT x.planilha_posto, public.sup_norm_nome(x.planilha_posto) = 'RENDATECNICA' AS rt
          FROM public."RH_POSTO_COLABORADOR" x
         WHERE x.empresa = p.empresa AND x.cadastro::text = p.cadastro
           AND x.contrato_id = p.contrato_id
      ) oc ON true
      LEFT JOIN pv pvo
             ON pvo.contrato_id = p.contrato_id AND oc.planilha_posto <> '' AND NOT oc.rt
            AND pvo.pn = public.sup_norm_nome(oc.planilha_posto)
      LEFT JOIN lig l
             ON l.contrato_id = p.contrato_id AND l.posto_senior = p.posto_senior
     WHERE p.contrato_id IS NOT NULL
  ),
  cids AS (
    SELECT contrato_id FROM pv
    UNION
    SELECT contrato_id FROM pes
  ),
  nos AS (
    SELECT c.nome AS ordem, jsonb_build_object(
      'id', c.id, 'nome', c.nome, 'cliente', c.cliente,
      'encerrado', COALESCE(c.status, 'ativo') = 'encerrado',
      'postos', COALESCE((
         SELECT jsonb_agg(jsonb_build_object('nome', pv.posto, 'vagas', pv.vagas, 'previsto', pv.vagas,
                                             'implantado', pv.implantado, 'implantado_registrado', pv.registrado)
                          ORDER BY pv.posto)
           FROM pv WHERE pv.contrato_id = c.id), '[]'::jsonb),
      'pessoas', COALESCE((
         SELECT jsonb_agg(jsonb_build_object(
                  'id', p.empregado_id, 'cadastro', p.cadastro, 'nome', p.nome, 'cargo', p.cargo,
                  'situacao', p.situacao, 'conta', public.rh_ac_conta_no_posto(p.situacao),
                  'posto_senior', p.posto_senior, 'posto', p.posto, 'fora', p.fora, 'origem', p.origem)
                  ORDER BY p.nome)
           FROM pes p WHERE p.contrato_id = c.id), '[]'::jsonb)
    ) AS no
      FROM cids JOIN public.contratos c ON c.id = cids.contrato_id
     WHERE COALESCE(c.status, 'ativo') <> 'encerrado'
        OR EXISTS (SELECT 1 FROM pes WHERE pes.contrato_id = c.id)
  )
  SELECT jsonb_build_object(
    'gerado_em', now(),
    'total_ativos', (SELECT count(*) FROM pessoas),
    'com_contrato', (SELECT count(*) FROM pessoas WHERE contrato_id IS NOT NULL),
    'contratos', COALESCE((SELECT jsonb_agg(no ORDER BY ordem) FROM nos), '[]'::jsonb),
    'todos_contratos', COALESCE((
       SELECT jsonb_agg(jsonb_build_object('id', c.id, 'nome', c.nome, 'cliente', c.cliente) ORDER BY c.nome)
         FROM public.contratos c WHERE COALESCE(c.status, 'ativo') <> 'encerrado'), '[]'::jsonb),
    'filiais_sem_contrato', COALESCE((
       SELECT jsonb_agg(jsonb_build_object('filial', f.filial, 'qtd', f.qtd) ORDER BY f.qtd DESC)
         FROM (SELECT COALESCE(filial, '(sem filial)') AS filial, count(*)::int AS qtd
                 FROM pessoas WHERE contrato_id IS NULL GROUP BY 1) f), '[]'::jsonb)
  ) INTO v_out;

  RETURN v_out;
END $$;
REVOKE ALL ON FUNCTION public.rh_ac_painel() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_ac_painel() TO authenticated;

-- ── 6. Operacional › Efetividade: previsto e implantado por contrato ────
-- Corpo igual ao da mig 20261026000090; pv sai da conta única e devolve
-- também 'implantado'.
CREATE OR REPLACE FUNCTION public.ope_efet_previsto_planilha()
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp
AS $fn$
DECLARE v_out jsonb;
BEGIN
  PERFORM public.ope_efet_exige('visualizar');

  WITH pessoas AS MATERIALIZED (
    SELECT e."Empresa" AS empresa, e."Filial" AS filial, a.contrato_id
      FROM public.rh_ac_ativos() a
      JOIN public."EMPREGADOS" e ON e."ID" = a.empregado_id
     WHERE a.contrato_id IS NOT NULL AND e."Empresa" IS NOT NULL AND e."Filial" IS NOT NULL
  ),
  liga AS (   -- quantos de cada filial caem em cada contrato
    SELECT empresa, filial, contrato_id, count(*) AS n FROM pessoas GROUP BY 1, 2, 3
  ),
  por_filial AS (   -- o contrato da filial: o de mais gente
    SELECT DISTINCT ON (empresa, filial) empresa, filial, contrato_id, n
      FROM liga ORDER BY empresa, filial, n DESC, contrato_id
  ),
  uma_vez AS (   -- o contrato fica só na filial em que tem mais gente
    SELECT DISTINCT ON (contrato_id) empresa, filial, contrato_id
      FROM por_filial ORDER BY contrato_id, n DESC, empresa, filial
  ),
  pv AS (
    SELECT b.contrato_id, sum(b.previsto) AS previsto, sum(b.implantado) AS implantado
      FROM public.contrato_postos_base(current_date) b
     WHERE NOT b.rt
     GROUP BY 1
  )
