-- ── 3. A conta única: previsto (planilha) + implantado vigente ──────────
-- Interna: só as RPCs SECURITY DEFINER abaixo a chamam (sem EXECUTE para o
-- client — ela não confere acesso).
CREATE OR REPLACE FUNCTION public.contrato_postos_base(p_data date DEFAULT current_date)
RETURNS TABLE (
  contrato_id uuid, posto text, posto_norm text, previsto numeric, implantado numeric,
  registrado boolean, rt boolean, justificativa text, vale_a_partir_de date,
  registrado_em timestamptz, registrado_por_nome text
)
LANGUAGE sql STABLE SET search_path = public, pg_temp
AS $fn$
  WITH pv AS (
    SELECT DISTINCT ON (pc.contrato_id, public.sup_norm_nome(pc.posto))
           pc.contrato_id, btrim(pc.posto) AS posto, public.sup_norm_nome(pc.posto) AS pn,
           COALESCE(pc.qt_postos, 0) AS vagas
      FROM public.planilha_custo pc
     WHERE pc.contrato_id IS NOT NULL
       AND pc.orexec = 'EXECUTADO'
       AND NOT COALESCE(pc.encerrado, false)
       AND pc.data_vigencia IS NOT NULL
       AND pc.data_vigencia <= p_data
       AND COALESCE(btrim(pc.posto), '') <> ''
     ORDER BY pc.contrato_id, public.sup_norm_nome(pc.posto), pc.data_vigencia DESC
  )
  SELECT pv.contrato_id, pv.posto, pv.pn, pv.vagas,
         COALESCE(i.implantado::numeric, pv.vagas),
         i.id IS NOT NULL,
         pv.pn = 'RENDATECNICA',
         i.justificativa, i.vale_a_partir_de, i.registrado_em, i.registrado_por_nome
    FROM pv
    LEFT JOIN LATERAL (
      SELECT x.id, x.implantado, x.justificativa, x.vale_a_partir_de, x.registrado_em, x.registrado_por_nome
        FROM public."CONTRATO_POSTO_IMPLANTADO" x
       WHERE x.contrato_id = pv.contrato_id AND x.posto_norm = pv.pn
         AND x.vale_a_partir_de <= p_data
       ORDER BY x.vale_a_partir_de DESC, x.registrado_em DESC
       LIMIT 1
    ) i ON true;
$fn$;
REVOKE ALL ON FUNCTION public.contrato_postos_base(date) FROM PUBLIC, anon, authenticated;

-- Início do ciclo anual vigente em p_data: o último aniversário da vigência
-- inicial (sem ela, data_inicio). NULL = contrato sem data, ou que ainda não
-- começou.
CREATE OR REPLACE FUNCTION public.contrato_ciclo_inicio(p_base date, p_data date DEFAULT current_date)
RETURNS date LANGUAGE sql IMMUTABLE SET search_path = public, pg_temp
AS $fn$
  SELECT CASE WHEN p_base IS NULL OR p_base > p_data THEN NULL
              ELSE (p_base + make_interval(years => extract(year FROM age(p_data, p_base))::int))::date END;
$fn$;

-- ── 4. Painel da aba Implantação ─────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.contrato_implantacao_painel()
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp
AS $fn$
DECLARE v_out jsonb;
BEGIN
  IF NOT public.has_screen_access(auth.uid(), 'licitacoes_contratos_implantacao', 'visualizar') THEN
    RAISE EXCEPTION 'Sem acesso à Implantação de Postos dos contratos.' USING ERRCODE = '42501';
  END IF;

  WITH b AS MATERIALIZED (
    SELECT * FROM public.contrato_postos_base(current_date) WHERE NOT rt
  ),
  c AS (
    SELECT ct.id, ct.nome, ct.cliente, ct.empresa_id,
           COALESCE(ct.vigencia_inicial, ct.data_inicio) AS base_ciclo,
           public.contrato_ciclo_inicio(COALESCE(ct.vigencia_inicial, ct.data_inicio)) AS ciclo
      FROM public.contratos ct
     WHERE COALESCE(ct.status, 'ativo') <> 'encerrado'
       AND EXISTS (SELECT 1 FROM b WHERE b.contrato_id = ct.id)
  )
  SELECT COALESCE(jsonb_agg(jsonb_build_object(
           'id', c.id, 'nome', c.nome, 'cliente', c.cliente, 'empresa_id', c.empresa_id,
           'base_ciclo', c.base_ciclo, 'ciclo_inicio', c.ciclo,
           'previsto', (SELECT sum(b.previsto) FROM b WHERE b.contrato_id = c.id),
           'implantado', (SELECT sum(b.implantado) FROM b WHERE b.contrato_id = c.id),
           -- Ciclo começou e algum posto não foi confirmado nele.
           'pendente', c.ciclo IS NOT NULL AND EXISTS (
              SELECT 1 FROM b WHERE b.contrato_id = c.id
                 AND (NOT b.registrado OR b.registrado_em::date < c.ciclo - 60)),
           'ultimo_registro', (SELECT max(b.registrado_em) FROM b WHERE b.contrato_id = c.id),
           'postos', (SELECT jsonb_agg(jsonb_build_object(
                        'posto', b.posto, 'previsto', b.previsto, 'implantado', b.implantado,
                        'registrado', b.registrado, 'justificativa', b.justificativa,
                        'vale_a_partir_de', b.vale_a_partir_de, 'registrado_em', b.registrado_em,
                        'registrado_por_nome', b.registrado_por_nome) ORDER BY b.posto)
                        FROM b WHERE b.contrato_id = c.id)
         ) ORDER BY c.nome), '[]'::jsonb)
    INTO v_out
    FROM c;

  RETURN v_out;
END $fn$;
REVOKE ALL ON FUNCTION public.contrato_implantacao_painel() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.contrato_implantacao_painel() TO authenticated;

