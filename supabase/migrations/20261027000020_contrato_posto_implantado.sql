-- =========================================================================
-- CONTRATOS — PREVISTO × IMPLANTADO, com justificativa anual da Licitação
-- (27/10/2026)
--
-- PEDIDO (chamado da Operação): "existe uma diferença entre o que foi
-- previsto na assinatura do contrato com o que de fato foi implantado" —
-- às vezes, até a pedido do tomador, o posto não é implantado. A Licitação
-- precisa registrar, a cada renovação, se vai implantar tudo o que está
-- previsto ou não (e por quê), e os supervisores precisam gerir o dia a dia
-- pelo IMPLANTADO, não pelo previsto.
--
-- O QUE JÁ EXISTIA
--   · Previsto = QT. PESSOAS da Planilha de Custo (EXECUTADO, vigente, um
--     posto por nome). A MESMA conta estava escrita duas vezes: rh_ac_painel
--     (Ativos/Contratos, mig 20261020000090) e ope_efet_previsto_planilha
--     (Efetividade, mig 20261026000090).
--   · CONTRATO_QUADRO_POSTO (mig 20260930000238) NÃO serve aqui: é o quadro
--     por FUNÇÃO de onde saem as vagas do Recrutamento. Misturar "o que
--     assinei para recrutar" com "o que está rodando" faria uma redução
--     pedida pelo tomador mexer na geração de vagas.
--
-- O QUE MUDA
--   1. "CONTRATO_POSTO_IMPLANTADO": histórico SÓ de inclusão, por contrato +
--      posto da planilha (a mesma chave do previsto: sup_norm_nome do nome).
--      Vale a linha mais recente com vale_a_partir_de <= a data — cobre a
--      renovação anual, a mudança no meio do ano a pedido do tomador, e
--      deixa a data passada usar o implantado que valia nela. Implantado
--      diferente do previsto exige justificativa (CHECK, não só a tela).
--   2. contrato_postos_base(p_data): A conta única — previsto da planilha +
--      implantado vigente. Posto sem registro: implantado = previsto
--      ("registrado" = false), para nada mudar no primeiro dia.
--      rh_ac_painel e ope_efet_previsto_planilha passam a ler dela.
--   3. Ciclo anual: começa no aniversário de vigencia_inicial (sem ela,
--      data_inicio). Contrato cujo ciclo começou e que tem posto sem registro
--      no ciclo (aceita registro feito até 60 dias ANTES do aniversário, que
--      é quando a renovação é negociada) fica "justificativa pendente".
--   4. Menu fantasma licitacoes_contratos_implantacao (aba Implantação em
--      Licitação › Contratos): visualizar lê, alterar registra. Escrita só
--      pela RPC (sem policy de INSERT), que confere o posto na planilha e
--      grava a foto do previsto do momento.
--
-- Idempotente. ROLLBACK no fim.
-- =========================================================================

-- ── 1. Tabela ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public."CONTRATO_POSTO_IMPLANTADO" (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contrato_id          uuid NOT NULL REFERENCES public.contratos(id) ON DELETE CASCADE,
  posto                text NOT NULL,
  posto_norm           text NOT NULL,
  -- Foto do previsto da planilha no momento do registro: se a planilha mudar
  -- depois, a justificativa continua fazendo sentido contra o que se via.
  previsto_no_registro numeric NOT NULL,
  implantado           integer NOT NULL CHECK (implantado >= 0),
  vale_a_partir_de     date NOT NULL DEFAULT current_date,
  justificativa        text,
  registrado_por       uuid,
  registrado_por_nome  text,
  registrado_em        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT contrato_posto_implantado_justifica
    CHECK (implantado = previsto_no_registro OR length(btrim(COALESCE(justificativa, ''))) >= 5)
);
CREATE INDEX IF NOT EXISTS idx_contrato_posto_implantado_vigente
  ON public."CONTRATO_POSTO_IMPLANTADO"(contrato_id, posto_norm, vale_a_partir_de DESC, registrado_em DESC);

