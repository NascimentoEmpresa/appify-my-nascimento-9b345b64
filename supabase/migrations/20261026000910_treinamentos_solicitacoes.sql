--
-- CHAMADO: "facilitar e padronizar as solicitações feitas pelos
-- encarregados, garantindo que o setor de Treinamentos receba todas as
-- informações necessárias de forma clara e completa. Hoje muitas
-- informações precisam ser solicitadas depois [...]. Queremos que o
-- encarregado confirme as informações antes do envio." Modelo anexo
-- (SOLICITAÇÃO DE TREINAMENTO.pdf): 5 etapas — Identificação, Necessidade,
-- Participantes, Estrutura e Confirmação — e o checklist do local (sala,
-- voltagem, projetor, internet, som/microfone, café, transporte), com a
-- declaração de responsabilidade e o "copiar informações para o ofício".
--
-- PEDIDO (Pablo): submódulo "Solicitar treinamento" no painel de
-- solicitações dos encarregados; ao enviar vai para o módulo Treinamentos,
-- submódulo novo "Solicitações de Treinamentos", onde quem tem permissão
-- aprova ou reprova, com chat como nos demais sistemas.
--
-- FLUXO / STATUS
--   pendente  → o encarregado enviou (com a declaração). Pode cancelar.
--   aprovada  → Treinamentos aprovou (pode já informar data/horário/instrutor).
--   agendada  → data e horário confirmados.
--   concluida → treinamento realizado.
--   reprovada (com motivo) · cancelada (pelo encarregado, ou por Treinamentos).
--   "Devolver para ajuste" volta a pendente com o motivo, e o encarregado
--   corrige e reenvia (trn_sol_reenviar).
--
-- CONVERSA: SISTEMA_COMENTARIOS (modulo 'treinamento'), o mesmo componente
-- dos outros sistemas (ConversaSolicitacao) dos dois lados.
--
-- PERMISSÕES (nenhuma concedida):
--   encarregados_solicitar_treinamento  /app/encarregados/solicitar-treinamento
--   treinamentos_solicitacoes           /app/treinamentos/solicitacoes
--     visualizar = ver todas; aprovar = aprovar/reprovar/devolver/agendar/
--     concluir/cancelar.
-- Idempotente. Branch local "treinamentos" — ainda não vai para a main.
-- =========================================================================

