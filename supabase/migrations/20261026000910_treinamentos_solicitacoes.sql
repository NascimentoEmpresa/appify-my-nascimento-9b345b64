-- ── 2) Tabelas ───────────────────────────────────────────────────────────
CREATE SEQUENCE IF NOT EXISTS public.trn_solicitacao_protocolo_seq;

CREATE TABLE IF NOT EXISTS public."TRN_SOLICITACAO" (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  protocolo           text UNIQUE,
  status              text NOT NULL DEFAULT 'pendente'
                        CHECK (status IN ('pendente', 'aprovada', 'agendada', 'concluida', 'reprovada', 'cancelada')),
  -- 1. Identificação
  solicitante_id      uuid NOT NULL DEFAULT auth.uid(),
  solicitante_nome    text,
  solicitante_email   text,
  contrato_empresa    bigint,
  contrato_filial     bigint,
  contrato_nome       text NOT NULL,
  -- 2. Necessidade
  treinamento         text NOT NULL,
  motivo              text NOT NULL,          -- por que é necessário
  objetivo            text,                   -- o que espera que aprendam
  assuntos            text NOT NULL,          -- o que precisa ser abordado
  -- 3. Participantes
  qtd_participantes   integer NOT NULL CHECK (qtd_participantes BETWEEN 1 AND 5000),
  equipe              text,
  turnos              text,
  -- 4. Estrutura
  modalidade          text NOT NULL DEFAULT 'presencial' CHECK (modalidade IN ('presencial', 'online', 'hibrida')),
  local_treinamento   text,                   -- local e endereço completo
  data_preferencial   date,
  horario_inicio      time,
  horario_fim         time,
  urgencia            text NOT NULL DEFAULT 'programavel' CHECK (urgencia IN ('programavel', 'prioritario')),
  recursos            text[] NOT NULL DEFAULT '{}',
  -- checklist do local
  tem_sala            boolean,
  voltagem            text CHECK (voltagem IS NULL OR voltagem IN ('110', '220', 'ambas')),
  tem_projetor        boolean,
  precisa_projetor    boolean,
  tem_internet        boolean,
  tem_som             boolean,
  tem_espaco_cafe     boolean,
  precisa_transporte  boolean,
  observacoes         text,
  -- 5. Confirmação
  declaracao          text,
  confirmado_em       timestamptz,
  -- Treinamentos
  decidido_por        text,
  decidido_em         timestamptz,
  motivo_reprovacao   text,
  devolucao_motivo    text,
  data_confirmada     date,
  horario_confirmado  text,
  instrutor           text,
  obs_treinamentos    text,
  concluida_em        timestamptz,
  cancelada_em        timestamptz,
  cancelada_por       text,
  cancelamento_motivo text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT trn_sol_horario CHECK (horario_inicio IS NULL OR horario_fim IS NULL OR horario_fim > horario_inicio)
);
CREATE INDEX IF NOT EXISTS idx_trn_sol_solicitante ON public."TRN_SOLICITACAO"(solicitante_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_trn_sol_status ON public."TRN_SOLICITACAO"(status, created_at DESC);

DROP TRIGGER IF EXISTS trg_trn_sol_updated ON public."TRN_SOLICITACAO";
CREATE TRIGGER trg_trn_sol_updated BEFORE UPDATE ON public."TRN_SOLICITACAO"
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE OR REPLACE FUNCTION public.trn_sol_protocolo()
RETURNS trigger LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
BEGIN
  IF NEW.protocolo IS NULL THEN
    NEW.protocolo := 'TRN-' || to_char(now(), 'YYYY') || '-' || lpad(nextval('public.trn_solicitacao_protocolo_seq')::text, 4, '0');
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_trn_sol_protocolo ON public."TRN_SOLICITACAO";
CREATE TRIGGER trg_trn_sol_protocolo BEFORE INSERT ON public."TRN_SOLICITACAO"
  FOR EACH ROW EXECUTE FUNCTION public.trn_sol_protocolo();

CREATE TABLE IF NOT EXISTS public."TRN_SOLICITACAO_EVENTO" (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitacao_id  bigint NOT NULL REFERENCES public."TRN_SOLICITACAO"(id) ON DELETE CASCADE,
  acao            text NOT NULL,   -- enviada | aprovada | agendada | concluida | reprovada | devolvida | reenviada | cancelada
  de_status       text,
  para_status     text,
  texto           text,
  autor_id        uuid DEFAULT auth.uid(),
  autor_nome      text,
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_trn_sol_evento ON public."TRN_SOLICITACAO_EVENTO"(solicitacao_id, created_at);

