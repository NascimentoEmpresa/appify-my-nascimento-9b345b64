-- =========================================================================
-- TREINAMENTOS — GERENCIAMENTO POR EMPRESA E CONTRATO (04/11/2026)
--
-- CHAMADO: área de gerenciamento dos treinamentos PRESENCIAIS organizada por
-- empresa (HAGG, NH, SN) e contrato: o treinamento em si (nome, tema, data,
-- horário, carga horária, responsável, local, observações), as fotos da
-- equipe no dia, a lista de presença assinada, as respostas das provinhas e
-- da pesquisa de satisfação (hoje em planilha — importação ou digitação) e
-- relatórios por empresa/contrato/treinamento/período/colaborador, mais o
-- relatório consolidado de um treinamento num documento só.
--
-- O QUE JÁ EXISTIA E NÃO SERVIA: a plataforma (mig 190) é de cursos ONLINE
-- (aluno, matrícula, aula, prova online); as Solicitações (mig 910) são o
-- PEDIDO do encarregado. Nada guardava o treinamento realizado no contrato.
--
-- DESENHO
--   Contrato NÃO ganha cadastro novo: é "CONTRATOS" (Empresa, Filial,
--   "NOME CONTRATO"). O treinamento guarda (empresa, filial) — a mesma chave
--   que TRN_SOLICITACAO usa — e uma cópia do nome (contrato renomeado ou
--   inativado não apaga o histórico).
--   TRN_CONTRATO_TREINAMENTO   o treinamento (opcionalmente ligado à solicitação).
--   TRN_CONTRATO_PARTICIPANTE  quem participou + presente/ausente. Colaborador
--                              vem de EMPREGADOS (empregado_id = "ID"); quem
--                              não estiver lá entra por nome/CPF.
--   TRN_CONTRATO_ARQUIVO       fotos (com data e legenda) e listas de presença
--                              assinadas, no bucket PRIVADO trn-contrato
--                              (trn-midia é público; aqui há rosto e assinatura).
--   TRN_CONTRATO_AVALIACAO     resultado das provinhas (nota 0–10).
--   TRN_CONTRATO_SATISFACAO    respostas da pesquisa (respostas jsonb + nota 0–10).
--   A leitura da planilha (colunas, "8 / 10", CPF) mora no front, em
--   src/lib/treinamentos/contratoTreinamento.ts, com teste.
--
-- ACESSO — menu novo `treinamentos_contratos` (/app/treinamentos/contratos),
-- nasce SEM ninguém: visualizar = ver tudo e os relatórios; incluir = criar
-- treinamento; alterar = editar e lançar fotos/presença/respostas;
-- excluir = apagar; exportar = baixar planilha/PDF dos relatórios.
--
-- Idempotente. ROLLBACK no fim.
-- =========================================================================

