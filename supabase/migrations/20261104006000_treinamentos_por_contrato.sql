-- O que vai dentro do treinamento: ler = visualizar; lançar, corrigir e
-- tirar = incluir ou alterar (quem cria o treinamento lança as fotos dele).
DO $$
DECLARE t text; p text;
BEGIN
  FOREACH t IN ARRAY ARRAY['TRN_CONTRATO_PARTICIPANTE','TRN_CONTRATO_ARQUIVO','TRN_CONTRATO_AVALIACAO','TRN_CONTRATO_SATISFACAO'] LOOP
    p := lower(replace(t, 'TRN_CONTRATO_', 'trn_ct_'));
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', p || '_sel', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING ((select public.trn_ct_acesso(''visualizar'')))', p || '_sel', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', p || '_ins', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR INSERT TO authenticated WITH CHECK ((select public.trn_ct_pode_lancar()))', p || '_ins', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', p || '_upd', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated USING ((select public.trn_ct_pode_lancar())) WITH CHECK ((select public.trn_ct_pode_lancar()))', p || '_upd', t);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', p || '_del', t);
    EXECUTE format('CREATE POLICY %I ON public.%I FOR DELETE TO authenticated USING ((select public.trn_ct_pode_lancar()) OR (select public.trn_ct_acesso(''excluir'')))', p || '_del', t);
  END LOOP;
END $$;

