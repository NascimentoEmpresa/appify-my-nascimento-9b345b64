CREATE TABLE IF NOT EXISTS public."TRN_CONTRATO_TREINAMENTO" (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa         bigint NOT NULL,
  filial          bigint NOT NULL,
  contrato_nome   text NOT NULL,
  nome            text NOT NULL,
  tema            text,
  data            date NOT NULL,
  horario_inicio  time,
  horario_fim     time,
  carga_horaria   numeric(6,2) CHECK (carga_horaria IS NULL OR carga_horaria BETWEEN 0 AND 999),
  responsavel     text,
  local           text,
  observacoes     text,
  solicitacao_id  bigint REFERENCES public."TRN_SOLICITACAO"(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  created_by      uuid DEFAULT auth.uid(),
