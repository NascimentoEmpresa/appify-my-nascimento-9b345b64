-- ── 5) RPCs de leitura ───────────────────────────────────────────────────
-- 5.1 Contratos com a contagem de treinamentos. Ativos sempre; inativos só
-- se já tiverem treinamento (histórico não some). _empresa NULL = todas.
CREATE OR REPLACE FUNCTION public.trn_ct_contratos(_empresa bigint DEFAULT NULL)
RETURNS TABLE (empresa bigint, filial bigint, nome text, ativo boolean, treinamentos bigint,
               participantes bigint, ultimo date)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
BEGIN
  IF NOT public.trn_ct_acesso('visualizar') THEN
    RAISE EXCEPTION 'Sem acesso a Treinamentos por Contrato.' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  WITH t AS (
    SELECT x.empresa, x.filial, count(*) AS n, max(x.data) AS ultimo, max(x.contrato_nome) AS nome,
           (SELECT count(*) FROM public."TRN_CONTRATO_PARTICIPANTE" p
              JOIN public."TRN_CONTRATO_TREINAMENTO" y ON y.id = p.treinamento_id
             WHERE y.empresa = x.empresa AND y.filial = x.filial AND p.presente) AS part
      FROM public."TRN_CONTRATO_TREINAMENTO" x
     WHERE _empresa IS NULL OR x.empresa = _empresa
     GROUP BY x.empresa, x.filial
  ), c AS (
    SELECT DISTINCT ON (k."Empresa", k."Filial") k."Empresa"::bigint AS empresa, k."Filial"::bigint AS filial,
           k."NOME CONTRATO"::text AS nome, (k."ATIVO" = 'SIM') AS ativo
      FROM public."CONTRATOS" k
     WHERE k."Empresa" IS NOT NULL AND k."Filial" IS NOT NULL
       AND (_empresa IS NULL OR k."Empresa" = _empresa)
     ORDER BY k."Empresa", k."Filial", (k."ATIVO" = 'SIM') DESC
  )
  SELECT COALESCE(c.empresa, t.empresa), COALESCE(c.filial, t.filial), COALESCE(c.nome, t.nome),
         COALESCE(c.ativo, false), COALESCE(t.n, 0), COALESCE(t.part, 0), t.ultimo
    FROM c FULL JOIN t ON t.empresa = c.empresa AND t.filial = c.filial
   WHERE COALESCE(c.ativo, false) OR t.n IS NOT NULL
   ORDER BY 3;
END $fn$;
REVOKE ALL ON FUNCTION public.trn_ct_contratos(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.trn_ct_contratos(bigint) TO authenticated;

-- 5.2 Colaboradores para a lista de participantes: os do contrato (não
-- demitidos) ou, com _busca, qualquer um pelo nome/CPF (gente de outro posto
-- também participa). Fonte única: EMPREGADOS.
CREATE OR REPLACE FUNCTION public.trn_ct_colaboradores(_empresa bigint, _filial bigint, _busca text DEFAULT NULL)
RETURNS TABLE (id bigint, nome text, cpf text, cargo text, contrato text, situacao text)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE b text := NULLIF(btrim(COALESCE(_busca, '')), '');
        d text := NULLIF(regexp_replace(COALESCE(_busca, ''), '\D', '', 'g'), '');
BEGIN
  IF NOT public.trn_ct_pode_lancar() THEN
    RAISE EXCEPTION 'Sem permissão para lançar participantes.' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  SELECT e."ID"::bigint, e."Nome"::text, e."CPF"::text, COALESCE(NULLIF(e."Título do Cargo", ''), NULLIF(e."Nome do Cargo", ''), e."Cargo"::text), e."Nome Filial"::text, e."Situação"::text
    FROM public."EMPREGADOS" e
   WHERE COALESCE(e."Situação", '') <> 'Demitido'
     AND (CASE WHEN b IS NULL THEN e."Empresa" = _empresa AND e."Filial" = _filial
               ELSE (e."Nome" ILIKE '%' || b || '%'
                     OR (d IS NOT NULL AND length(d) >= 4 AND regexp_replace(COALESCE(e."CPF"::text, ''), '\D', '', 'g') LIKE d || '%')) END)
   ORDER BY (e."Empresa" = _empresa AND e."Filial" = _filial) DESC, e."Nome"
   LIMIT CASE WHEN b IS NULL THEN 2000 ELSE 50 END;
END $fn$;
REVOKE ALL ON FUNCTION public.trn_ct_colaboradores(bigint, bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.trn_ct_colaboradores(bigint, bigint, text) TO authenticated;

-- 5.3 Solicitações aceitas/agendadas/realizadas do contrato, para "registrar
-- a partir da solicitação" já trazer data, horário e local. Só as que ainda
-- não viraram treinamento.
CREATE OR REPLACE FUNCTION public.trn_ct_solicitacoes(_empresa bigint, _filial bigint)
RETURNS TABLE (id bigint, protocolo text, treinamento text, assuntos text, local_treinamento text,
               data date, horario_inicio time, horario_fim time, instrutor text, status text)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
BEGIN
  IF NOT public.trn_ct_acesso('incluir') THEN
    RAISE EXCEPTION 'Sem permissão para registrar treinamento.' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  SELECT s.id, s.protocolo, s.treinamento, s.assuntos, s.local_treinamento,
         COALESCE(s.data_confirmada, s.data_preferencial), s.horario_inicio, s.horario_fim, s.instrutor, s.status
    FROM public."TRN_SOLICITACAO" s
   WHERE s.contrato_empresa = _empresa AND s.contrato_filial = _filial
     AND s.status IN ('aprovada', 'agendada', 'concluida')
     AND NOT EXISTS (SELECT 1 FROM public."TRN_CONTRATO_TREINAMENTO" t WHERE t.solicitacao_id = s.id)
   ORDER BY COALESCE(s.data_confirmada, s.data_preferencial) DESC NULLS LAST;
END $fn$;
REVOKE ALL ON FUNCTION public.trn_ct_solicitacoes(bigint, bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.trn_ct_solicitacoes(bigint, bigint) TO authenticated;

