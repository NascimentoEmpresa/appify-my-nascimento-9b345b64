CREATE OR REPLACE FUNCTION public.trn_ct_acesso(_acao text DEFAULT 'visualizar')
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT auth.uid() IS NOT NULL AND public.can_access(auth.uid(), 'treinamentos_contratos', _acao::public.app_acao)
$$;
REVOKE ALL ON FUNCTION public.trn_ct_acesso(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.trn_ct_acesso(text) TO authenticated;

-- Lançar coisa dentro de um treinamento (foto, presença, resposta) vale para
-- quem cria OU edita.
CREATE OR REPLACE FUNCTION public.trn_ct_pode_lancar()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT public.trn_ct_acesso('incluir') OR public.trn_ct_acesso('alterar')
$$;
REVOKE ALL ON FUNCTION public.trn_ct_pode_lancar() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.trn_ct_pode_lancar() TO authenticated;

