-- ── 6) Opções da criação: contratos com responsáveis + usuários ──────────
-- tem_acesso = a pessoa já enxerga a tela Encarregados › Documentos.
CREATE OR REPLACE FUNCTION public.rh_doc_opcoes()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
BEGIN
  IF NOT public.rh_doc_pode('incluir') AND NOT public.rh_doc_pode('alterar') THEN
    RAISE EXCEPTION 'Sem permissão para solicitar documentos.' USING ERRCODE = '42501';
  END IF;
  RETURN jsonb_build_object(
    'contratos', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
               'empresa', c."Empresa", 'filial', c."Filial", 'nome', c."NOME CONTRATO", 'empresa_nome', c."NOME EMPRESA",
               'responsaveis', COALESCE((
                 SELECT jsonb_agg(DISTINCT jsonb_build_object(
                          'empregado_id', r.empregado_id, 'auth_user_id', r.auth_user_id,
                          'nome', e."Nome", 'posto', r.posto_lider,
                          'tem_acesso', r.auth_user_id IS NOT NULL
                                        AND public.can_access(r.auth_user_id, 'encarregados_documentos', 'visualizar'::public.app_acao)))
                   FROM public.rh_hier_responsaveis() r
                   LEFT JOIN public."EMPREGADOS" e ON e."ID" = r.empregado_id
                  WHERE r.empresa = c."Empresa" AND r.filial = c."Filial"), '[]'::jsonb))
             ORDER BY c."NOME CONTRATO")
        FROM public."CONTRATOS" c WHERE c."ATIVO" = 'SIM'), '[]'::jsonb),
    'usuarios', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
               'id', p.id, 'nome', COALESCE(public.rh_doc_nome_usuario(p.id), p.email), 'email', p.email,
               'tem_acesso', public.can_access(p.id, 'encarregados_documentos', 'visualizar'::public.app_acao))
             ORDER BY COALESCE(public.rh_doc_nome_usuario(p.id), p.email))
        FROM public.profiles p
        JOIN auth.users u ON u.id = p.id
       WHERE u.banned_until IS NULL OR u.banned_until < now()), '[]'::jsonb));
END $fn$;
REVOKE ALL ON FUNCTION public.rh_doc_opcoes() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_doc_opcoes() TO authenticated;

-- Confere o destinatário. Com contrato: tem que ser um dos responsáveis
-- dele na Hierarquia, e com login vinculado. Devolve (nome, empregado_id).
CREATE OR REPLACE FUNCTION public.rh_doc_validar_destino(_empresa bigint, _filial bigint, _dest uuid,
  OUT nome text, OUT empregado_id bigint, OUT contrato_nome text)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
BEGIN
  IF _dest IS NULL THEN RAISE EXCEPTION 'Escolha quem vai receber a solicitação.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM auth.users WHERE id = _dest) THEN RAISE EXCEPTION 'Usuário não encontrado.'; END IF;
  IF _empresa IS NOT NULL THEN
    SELECT c."NOME CONTRATO" INTO contrato_nome FROM public."CONTRATOS" c
     WHERE c."Empresa" = _empresa AND c."Filial" = _filial LIMIT 1;
    IF contrato_nome IS NULL THEN RAISE EXCEPTION 'Contrato não encontrado.'; END IF;
    SELECT r.empregado_id INTO empregado_id FROM public.rh_hier_responsaveis() r
     WHERE r.empresa = _empresa AND r.filial = _filial AND r.auth_user_id = _dest LIMIT 1;
    IF empregado_id IS NULL THEN
      RAISE EXCEPTION 'Essa pessoa não é responsável pelo contrato % na Hierarquia de Postos.', contrato_nome;
    END IF;
  END IF;
  nome := public.rh_doc_nome_usuario(_dest);
END $fn$;
REVOKE ALL ON FUNCTION public.rh_doc_validar_destino(bigint, bigint, uuid) FROM PUBLIC, anon, authenticated;

-- ── 7) Solicitar ─────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.rh_doc_solicitar(p jsonb)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE
  v_tit  text := NULLIF(btrim(p->>'titulo'), '');
  v_desc text := NULLIF(btrim(p->>'descricao'), '');
  v_emp  bigint := NULLIF(p->>'contrato_empresa', '')::bigint;
  v_fil  bigint := NULLIF(p->>'contrato_filial', '')::bigint;
  v_dest uuid := NULLIF(p->>'destinatario_id', '')::uuid;
  v_prazo date := NULLIF(p->>'prazo', '')::date;
  v_d    record;
  v_eu   text := public.rh_doc_nome_usuario(auth.uid());
  v_id   bigint;
BEGIN
  IF NOT public.rh_doc_pode('incluir') THEN
    RAISE EXCEPTION 'Sem permissão para solicitar documentos.' USING ERRCODE = '42501';
  END IF;
  IF v_tit IS NULL THEN RAISE EXCEPTION 'Informe o título.'; END IF;
  IF v_desc IS NULL THEN RAISE EXCEPTION 'Descreva o que está sendo solicitado.'; END IF;
  IF (v_emp IS NULL) <> (v_fil IS NULL) THEN RAISE EXCEPTION 'Contrato incompleto.'; END IF;
  SELECT * INTO v_d FROM public.rh_doc_validar_destino(v_emp, v_fil, v_dest);

  INSERT INTO public."RH_DOCUMENTO_SOLICITACAO"
    (titulo, descricao, contrato_empresa, contrato_filial, contrato_nome, destinatario_id, destinatario_nome,
     destinatario_empregado_id, solicitante_nome, prazo)
  VALUES (v_tit, v_desc, v_emp, v_fil, v_d.contrato_nome, v_dest, v_d.nome, v_d.empregado_id, v_eu, v_prazo)
  RETURNING id INTO v_id;

  INSERT INTO public."RH_DOCUMENTO_EVENTO" (solicitacao_id, acao, texto, autor_nome, lado)
  VALUES (v_id, 'criada', 'Para ' || coalesce(v_d.nome, '—') || coalesce(' — ' || v_d.contrato_nome, ''), v_eu, 'rh');

  INSERT INTO public.notificacoes (user_id, titulo, mensagem, tipo, link)
  VALUES (v_dest, 'Documento solicitado pelo RH',
          v_tit || coalesce(' — ' || v_d.contrato_nome, '') || coalesce('. Prazo: ' || to_char(v_prazo, 'DD/MM/YYYY'), '') || '.',
          'rh_documento_solicitado', '/app/encarregados/documentos?s=' || v_id);
  RETURN v_id;
END $fn$;
REVOKE ALL ON FUNCTION public.rh_doc_solicitar(jsonb) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_doc_solicitar(jsonb) TO authenticated;

-- ── 8) Anexos ────────────────────────────────────────────────────────────
-- A origem sai de quem anexa: o destinatário anexa como 'destinatario'
-- (mesmo que também seja do RH); os demais, como 'rh'.
CREATE OR REPLACE FUNCTION public.rh_doc_anexo_registrar(p_solicitacao bigint, p_path text, p_nome text, p_mime text, p_tamanho bigint)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE
  v_s  public."RH_DOCUMENTO_SOLICITACAO";
  v_id bigint;
BEGIN
  SELECT * INTO v_s FROM public."RH_DOCUMENTO_SOLICITACAO" WHERE id = p_solicitacao;
  IF NOT FOUND THEN RAISE EXCEPTION 'Solicitação não encontrada.'; END IF;
  IF NOT public.rh_doc_pode_anexar(p_solicitacao) THEN
    RAISE EXCEPTION 'Só dá para anexar em solicitação pendente, sendo o destinatário ou o RH.' USING ERRCODE = '42501';
  END IF;
  IF public.rh_doc_id_do_caminho(p_path) IS DISTINCT FROM p_solicitacao THEN RAISE EXCEPTION 'Caminho inválido.'; END IF;
  INSERT INTO public."RH_DOCUMENTO_ANEXO" (solicitacao_id, origem, storage_path, nome_arquivo, mime_type, tamanho_bytes, enviado_por)
  VALUES (p_solicitacao, CASE WHEN v_s.destinatario_id = auth.uid() THEN 'destinatario' ELSE 'rh' END,
          p_path, p_nome, p_mime, p_tamanho, public.rh_doc_nome_usuario(auth.uid()))
  RETURNING id INTO v_id;
  RETURN v_id;
END $fn$;
REVOKE ALL ON FUNCTION public.rh_doc_anexo_registrar(bigint, text, text, text, bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_doc_anexo_registrar(bigint, text, text, text, bigint) TO authenticated;

-- Apaga o registro e devolve o caminho (a tela apaga o arquivo). Cada lado
-- só apaga o que ele mesmo anexou.
CREATE OR REPLACE FUNCTION public.rh_doc_anexo_remover(p_id bigint)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE v public."RH_DOCUMENTO_ANEXO";
BEGIN
  SELECT * INTO v FROM public."RH_DOCUMENTO_ANEXO" WHERE id = p_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Anexo não encontrado.'; END IF;
  IF NOT public.rh_doc_pode_anexar(v.solicitacao_id) THEN
    RAISE EXCEPTION 'A solicitação não está pendente.' USING ERRCODE = '42501';
  END IF;
  IF v.enviado_por_id IS DISTINCT FROM auth.uid() AND NOT public.rh_doc_pode('alterar') THEN
    RAISE EXCEPTION 'Só quem anexou pode remover o arquivo.' USING ERRCODE = '42501';
  END IF;
  DELETE FROM public."RH_DOCUMENTO_ANEXO" WHERE id = p_id;
  RETURN v.storage_path;
END $fn$;
REVOKE ALL ON FUNCTION public.rh_doc_anexo_remover(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_doc_anexo_remover(bigint) TO authenticated;

-- ── 9) Mensagem ──────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.rh_doc_mensagem(p_id bigint, p_texto text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE
  v_s   public."RH_DOCUMENTO_SOLICITACAO";
  v_txt text := NULLIF(btrim(p_texto), '');
  v_eu  text := public.rh_doc_nome_usuario(auth.uid());
  v_dest boolean;
BEGIN
  SELECT * INTO v_s FROM public."RH_DOCUMENTO_SOLICITACAO" WHERE id = p_id;
  IF NOT FOUND OR NOT public.rh_doc_pode_ver(p_id) THEN RAISE EXCEPTION 'Solicitação não encontrada.'; END IF;
  IF v_txt IS NULL THEN RAISE EXCEPTION 'Escreva a mensagem.'; END IF;
  v_dest := v_s.destinatario_id = auth.uid();
  INSERT INTO public."RH_DOCUMENTO_EVENTO" (solicitacao_id, acao, texto, autor_nome, lado)
  VALUES (p_id, 'mensagem', v_txt, v_eu, CASE WHEN v_dest THEN 'destinatario' ELSE 'rh' END);
  -- Avisa o outro lado: do destinatário vai para quem solicitou; do RH, para o destinatário.
  INSERT INTO public.notificacoes (user_id, titulo, mensagem, tipo, link)
  VALUES (CASE WHEN v_dest THEN v_s.solicitante_id ELSE v_s.destinatario_id END,
          'Mensagem em documento solicitado', v_s.titulo || ' — ' || coalesce(v_eu, '') || ': ' || left(v_txt, 200),
          'rh_documento_mensagem',
          CASE WHEN v_dest THEN '/app/rh/documentos?s=' ELSE '/app/encarregados/documentos?s=' END || p_id);
END $fn$;
REVOKE ALL ON FUNCTION public.rh_doc_mensagem(bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_doc_mensagem(bigint, text) TO authenticated;

-- ── 10) Destinatário envia → concluída ───────────────────────────────────
CREATE OR REPLACE FUNCTION public.rh_doc_concluir(p_id bigint, p_observacao text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $fn$
DECLARE
  v_s   public."RH_DOCUMENTO_SOLICITACAO";
  v_obs text := NULLIF(btrim(p_observacao), '');
  v_eu  text := public.rh_doc_nome_usuario(auth.uid());
BEGIN
  SELECT * INTO v_s FROM public."RH_DOCUMENTO_SOLICITACAO" WHERE id = p_id FOR UPDATE;
  IF NOT FOUND OR v_s.destinatario_id IS DISTINCT FROM auth.uid() THEN
    RAISE EXCEPTION 'Só o destinatário envia o documento.' USING ERRCODE = '42501';
  END IF;
  IF v_s.status <> 'pendente' THEN RAISE EXCEPTION 'A solicitação não está pendente (está %).', v_s.status; END IF;
  IF NOT EXISTS (SELECT 1 FROM public."RH_DOCUMENTO_ANEXO" WHERE solicitacao_id = p_id AND origem = 'destinatario') THEN
    RAISE EXCEPTION 'Anexe o documento antes de enviar.';
  END IF;
  UPDATE public."RH_DOCUMENTO_SOLICITACAO"
     SET status = 'concluida', concluida_em = now(), concluida_por = v_eu, observacao_envio = v_obs
   WHERE id = p_id;
  INSERT INTO public."RH_DOCUMENTO_EVENTO" (solicitacao_id, acao, texto, autor_nome, lado)
  VALUES (p_id, 'concluida', v_obs, v_eu, 'destinatario');
  INSERT INTO public.notificacoes (user_id, titulo, mensagem, tipo, link)
  VALUES (v_s.solicitante_id, 'Documento devolvido assinado',
          v_s.titulo || ' — ' || coalesce(v_eu, '') || coalesce(' — ' || v_s.contrato_nome, '') || coalesce('. Obs.: ' || left(v_obs, 200), ''),
          'rh_documento_concluido', '/app/rh/documentos?s=' || p_id);
END $fn$;
REVOKE ALL ON FUNCTION public.rh_doc_concluir(bigint, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_doc_concluir(bigint, text) TO authenticated;

