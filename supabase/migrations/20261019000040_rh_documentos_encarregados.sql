-- ── 2) Tabelas ───────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public."RH_DOCUMENTO_SOLICITACAO" (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo             text   NOT NULL CHECK (length(btrim(titulo)) > 0),
  descricao          text,
  contrato_empresa   bigint,                 -- NULL = enviado direto a um usuário
  contrato_filial    bigint,
  contrato_nome      text,
  destinatario_id    uuid   NOT NULL,        -- auth.users
  destinatario_nome  text,
  destinatario_empregado_id bigint,          -- EMPREGADOS."ID", quando veio da Hierarquia
  solicitante_id     uuid   NOT NULL DEFAULT auth.uid(),
  solicitante_nome   text,
  prazo              date,
  status             text   NOT NULL DEFAULT 'pendente'
                       CHECK (status IN ('pendente', 'concluida', 'cancelada')),
  observacao_envio   text,                   -- a do destinatário ao concluir
  concluida_em       timestamptz,
  concluida_por      text,
  cancelada_em       timestamptz,
  cancelada_por      text,
  cancelamento_motivo text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT rds_contrato_par CHECK ((contrato_empresa IS NULL) = (contrato_filial IS NULL))
);
CREATE INDEX IF NOT EXISTS idx_rds_destinatario ON public."RH_DOCUMENTO_SOLICITACAO"(destinatario_id, status);
CREATE INDEX IF NOT EXISTS idx_rds_status ON public."RH_DOCUMENTO_SOLICITACAO"(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_rds_contrato ON public."RH_DOCUMENTO_SOLICITACAO"(contrato_empresa, contrato_filial);

DROP TRIGGER IF EXISTS trg_rds_updated ON public."RH_DOCUMENTO_SOLICITACAO";
CREATE TRIGGER trg_rds_updated BEFORE UPDATE ON public."RH_DOCUMENTO_SOLICITACAO"
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE IF NOT EXISTS public."RH_DOCUMENTO_ANEXO" (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitacao_id  bigint NOT NULL REFERENCES public."RH_DOCUMENTO_SOLICITACAO"(id) ON DELETE CASCADE,
  origem          text   NOT NULL CHECK (origem IN ('rh', 'destinatario')),
  storage_path    text   NOT NULL,
  nome_arquivo    text,
  mime_type       text,
  tamanho_bytes   bigint,
  enviado_por_id  uuid   DEFAULT auth.uid(),
  enviado_por     text,
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rda_solicitacao ON public."RH_DOCUMENTO_ANEXO"(solicitacao_id);

-- Histórico e conversa no mesmo lugar: acao = 'mensagem' é texto livre de
-- qualquer um dos lados; o resto é o registro das mudanças de status.
CREATE TABLE IF NOT EXISTS public."RH_DOCUMENTO_EVENTO" (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitacao_id  bigint NOT NULL REFERENCES public."RH_DOCUMENTO_SOLICITACAO"(id) ON DELETE CASCADE,
  acao            text   NOT NULL,   -- criada | mensagem | concluida | devolvida | reencaminhada | cancelada
  texto           text,
  autor_id        uuid   DEFAULT auth.uid(),
  autor_nome      text,
  lado            text   CHECK (lado IN ('rh', 'destinatario')),
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rde_solicitacao ON public."RH_DOCUMENTO_EVENTO"(solicitacao_id, created_at);

-- ── 3) Quem é quem ───────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.rh_doc_eh_rh()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT auth.uid() IS NOT NULL AND public.can_access(auth.uid(), 'rh_documentos', 'visualizar'::public.app_acao)
$$;
CREATE OR REPLACE FUNCTION public.rh_doc_pode(_acao text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT auth.uid() IS NOT NULL AND public.can_access(auth.uid(), 'rh_documentos', _acao::public.app_acao)
$$;
CREATE OR REPLACE FUNCTION public.rh_doc_pode_ver(_id bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT EXISTS (SELECT 1 FROM public."RH_DOCUMENTO_SOLICITACAO" s
                  WHERE s.id = _id AND (s.destinatario_id = auth.uid() OR public.rh_doc_eh_rh()))
$$;
-- Subir/apagar arquivo: só com a solicitação pendente — o RH (incluir ou
-- alterar) os originais, o destinatário os assinados.
CREATE OR REPLACE FUNCTION public.rh_doc_pode_anexar(_id bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT EXISTS (SELECT 1 FROM public."RH_DOCUMENTO_SOLICITACAO" s
                  WHERE s.id = _id AND s.status = 'pendente'
                    AND (s.destinatario_id = auth.uid()
                         OR public.rh_doc_pode('incluir') OR public.rh_doc_pode('alterar')))
$$;
REVOKE ALL ON FUNCTION public.rh_doc_eh_rh(), public.rh_doc_pode(text), public.rh_doc_pode_ver(bigint), public.rh_doc_pode_anexar(bigint) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_doc_eh_rh(), public.rh_doc_pode(text), public.rh_doc_pode_ver(bigint), public.rh_doc_pode_anexar(bigint) TO authenticated;

CREATE OR REPLACE FUNCTION public.rh_doc_nome_usuario(_uid uuid)
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  SELECT COALESCE(
    (SELECT e."Nome" FROM public."EMPREGADOS" e WHERE e.auth_user_id = _uid
      ORDER BY (e."Situação" = 'Trabalhando') DESC, e."ID" DESC LIMIT 1),
    (SELECT NULLIF(btrim(p.display_name), '') FROM public.profiles p WHERE p.id = _uid),
    (SELECT p.email FROM public.profiles p WHERE p.id = _uid))
$$;
REVOKE ALL ON FUNCTION public.rh_doc_nome_usuario(uuid) FROM PUBLIC, anon, authenticated;

