-- =========================================================================
-- RH › DOCUMENTOS  ×  ENCARREGADOS › DOCUMENTOS (19/10/2026)
--
-- CHAMADO: "solicito que seja criado na aba Encarregados um local onde o RH
-- envia os documentos para os mesmos, eles recolhem a assinatura e anexam o
-- documento, e que fique pendente o retorno até o momento do anexo."
-- Observação do solicitante: "documentos muitas vezes são extraviados e não
-- retornam ao RH como deveria."
--
-- PEDIDO (Pablo): o RH SOLICITA formalmente — título, descrição, contrato e
-- o responsável por aquele contrato (o mesmo da Conferência de Ponto, que
-- sai da Hierarquia de Postos: rh_hier_responsaveis, mig 20261008000005).
-- Sem contrato, pode escolher um usuário do sistema. A solicitação fica
-- "Pendente (FULANO — CONTRATO)" até o destinatário anexar o documento e
-- enviar; aí vira "Concluída". O destinatário pode deixar observação no
-- envio; os dois lados conversam pelas mensagens da solicitação.
--
-- O FLUXO
--   RH cria (pendente) → pode anexar o documento a assinar (origem 'rh')
--   Destinatário baixa, colhe a assinatura, anexa (origem 'destinatario')
--   e envia com observação → concluída. Sem anexo dele, não conclui.
--   RH pode DEVOLVER uma concluída (motivo) → volta a pendente,
--   REENCAMINHAR uma pendente a outra pessoa, ou CANCELAR (motivo).
--   Cada passo vira evento no histórico e notifica o outro lado.
--
-- QUEM VÊ
--   RH (rh_documentos/visualizar): todas.
--   Destinatário: as que são dele — pela pessoa, não pelo menu, para que o
--   "usuário do sistema" escolhido sem contrato também enxergue. A TELA
--   (/app/encarregados/documentos) continua exigindo o menu
--   encarregados_documentos; a lista de pessoas na criação avisa quem ainda
--   não tem esse acesso.
--
-- PERMISSÕES — nenhuma concedida. Menus criados:
--   rh_documentos            (RH: visualizar = ver; incluir = solicitar;
--                             alterar = devolver/reencaminhar/cancelar)
--   encarregados_documentos  (Encarregados: receber e anexar)
-- Liberar em Administração › Acesso por Usuário.
--
-- Idempotente.
-- =========================================================================

