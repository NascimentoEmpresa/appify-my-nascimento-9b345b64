-- ── 2) Tabelas ───────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public."RH_POSTO_TRABALHO" (
  codigo             text PRIMARY KEY,                -- PO-00001 (como na Senior)
  estrutura          integer NOT NULL DEFAULT 3,      -- 003 Hagg 2026
  descricao          text NOT NULL,                   -- 01-1099-0071-0061-06-RECEPCIONISTA-A 30H 5X2
  descricao_reduzida text,
  -- A descrição da Senior carrega o endereço do posto: empresa-filial-
  -- local-cargo-sindicato-título. Separado aqui para filtrar e juntar.
  empresa            integer,
  filial             integer,
  local_cod          text,
  cargo_cod          text,
  sindicato_cod      text,
  titulo             text,
  vagas              integer,
  observacao         text,
  criado_senior      date,
  ativo              boolean NOT NULL DEFAULT true,
  atualizado_em      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rh_posto_filial ON public."RH_POSTO_TRABALHO"(empresa, filial);

CREATE TABLE IF NOT EXISTS public."RH_POSTO_HIERARQUIA" (
  posto_codigo     text PRIMARY KEY REFERENCES public."RH_POSTO_TRABALHO"(codigo) ON DELETE CASCADE,
  pai_codigo       text REFERENCES public."RH_POSTO_TRABALHO"(codigo),
  ordem            integer NOT NULL DEFAULT 0,
  tipo_hierarquia  integer NOT NULL DEFAULT 2,       -- 002 HIERARQUIA DE PONTO
  revisao          integer NOT NULL DEFAULT 1,
  origem           text NOT NULL DEFAULT 'senior' CHECK (origem IN ('senior', 'erp')),
  alterado_por     text,
  alterado_em      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT rh_hier_sem_auto_pai CHECK (pai_codigo IS NULL OR pai_codigo <> posto_codigo)
);
CREATE INDEX IF NOT EXISTS idx_rh_hier_pai ON public."RH_POSTO_HIERARQUIA"(pai_codigo);

CREATE TABLE IF NOT EXISTS public."RH_POSTO_HIERARQUIA_HIST" (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  posto_codigo  text NOT NULL,
  pai_antes     text,
  pai_depois    text,
  motivo        text,
  autor_id      uuid DEFAULT auth.uid(),
  autor_nome    text,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rh_hier_hist_posto ON public."RH_POSTO_HIERARQUIA_HIST"(posto_codigo, created_at DESC);

