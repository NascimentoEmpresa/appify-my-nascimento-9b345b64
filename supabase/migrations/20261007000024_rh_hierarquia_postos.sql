-- "Minha área": os postos que o usuário logado ocupa (pelo cadastro dele na
-- Senior, EMPREGADOS.auth_user_id), tudo o que está abaixo deles, os
-- contratos (empresa+filial) e quantos colaboradores. É a base do controle
-- de ponto / acesso por contrato. Só devolve a do próprio usuário.
CREATE OR REPLACE FUNCTION public.rh_hier_minha_area()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_meus text[];
BEGIN
  IF auth.uid() IS NULL THEN RETURN NULL; END IF;
  SELECT array_agg(DISTINCT e."Posto") INTO v_meus
    FROM public."EMPREGADOS" e
   WHERE e.auth_user_id = auth.uid() AND COALESCE(e."Situação", '') <> 'Demitido'
     AND e."Posto" IN (SELECT codigo FROM public."RH_POSTO_TRABALHO");
  RETURN (
    WITH area AS (
      SELECT DISTINCT d.codigo FROM unnest(COALESCE(v_meus, '{}')) m(p), LATERAL public.rh_hier_descendentes(m.p) d
    )
    SELECT jsonb_build_object(
      'meus_postos', COALESCE(to_jsonb(v_meus), '[]'::jsonb),
      'postos', COALESCE((SELECT jsonb_agg(codigo ORDER BY codigo) FROM area), '[]'::jsonb),
      'contratos', COALESCE((SELECT jsonb_agg(DISTINCT jsonb_build_object('empresa', p.empresa, 'filial', p.filial))
                               FROM public."RH_POSTO_TRABALHO" p WHERE p.codigo IN (SELECT codigo FROM area)), '[]'::jsonb),
      'colaboradores', COALESCE((SELECT count(*) FROM public."EMPREGADOS" e
                                  WHERE e."Posto" IN (SELECT codigo FROM area) AND COALESCE(e."Situação", '') <> 'Demitido'), 0)));
END $$;
REVOKE ALL ON FUNCTION public.rh_hier_minha_area() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_hier_minha_area() TO authenticated;

-- ── 7) Painel (tudo de uma vez: postos, árvore, ocupantes, contratos) ────
CREATE OR REPLACE FUNCTION public.rh_hier_painel()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
  IF NOT public.rh_hier_pode() THEN
    RAISE EXCEPTION 'Sem acesso à Hierarquia de Postos.' USING ERRCODE = '42501';
  END IF;
  RETURN jsonb_build_object(
    -- [codigo, descricao, titulo, empresa, filial, cargo_cod, vagas, pai, ordem, na_hierarquia, origem]
    'postos', COALESCE((SELECT jsonb_agg(jsonb_build_array(p.codigo, p.descricao, p.titulo, p.empresa, p.filial, p.cargo_cod,
                          p.vagas, h.pai_codigo, COALESCE(h.ordem, 0), h.posto_codigo IS NOT NULL, h.origem) ORDER BY p.codigo)
                         FROM public."RH_POSTO_TRABALHO" p
                         LEFT JOIN public."RH_POSTO_HIERARQUIA" h ON h.posto_codigo = p.codigo
                        WHERE p.ativo), '[]'::jsonb),
    -- [id, nome, cadastro, cargo, situação, posto, tem_login, empresa, filial, nome do posto na Senior]
    'ocupantes', COALESCE((SELECT jsonb_agg(jsonb_build_array(e."ID", e."Nome", e."Cadastro", e."Título do Cargo", e."Situação",
                          e."Posto", e.auth_user_id IS NOT NULL, e."Empresa", e."Filial", e."Nome do Posto") ORDER BY e."Nome")
                           FROM public."EMPREGADOS" e
                          WHERE COALESCE(e."Situação", '') <> 'Demitido' AND COALESCE(e."Nome", '') NOT ILIKE '%teste%'), '[]'::jsonb),
    -- [empresa, filial, nome, ativo]
    'contratos', COALESCE((SELECT jsonb_agg(jsonb_build_array(c."Empresa", c."Filial", c."NOME CONTRATO", c."ATIVO" = 'SIM'))
                           FROM public."CONTRATOS" c), '[]'::jsonb),
    'historico', COALESCE((SELECT jsonb_agg(to_jsonb(x) ORDER BY x.created_at DESC)
                           FROM (SELECT * FROM public."RH_POSTO_HIERARQUIA_HIST" ORDER BY created_at DESC LIMIT 200) x), '[]'::jsonb),
    'pode_alterar', public.rh_hier_pode('alterar'));
END $$;
REVOKE ALL ON FUNCTION public.rh_hier_painel() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_hier_painel() TO authenticated;

-- ── 8) Mover um posto (ERP) — com trava de ciclo e histórico ─────────────
CREATE OR REPLACE FUNCTION public.rh_hier_mover(p_posto text, p_novo_pai text, p_motivo text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_antes text;
  v_nome  text := (SELECT coalesce(display_name, email) FROM public.profiles WHERE id = auth.uid());
BEGIN
  IF NOT public.rh_hier_pode('alterar') THEN
    RAISE EXCEPTION 'Sem permissão para alterar a hierarquia.' USING ERRCODE = '42501';
  END IF;
  IF btrim(coalesce(p_motivo, '')) = '' THEN RAISE EXCEPTION 'Informe o motivo da mudança.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public."RH_POSTO_TRABALHO" WHERE codigo = p_posto) THEN RAISE EXCEPTION 'Posto % não existe.', p_posto; END IF;
  IF p_novo_pai IS NOT NULL THEN
    IF NOT EXISTS (SELECT 1 FROM public."RH_POSTO_TRABALHO" WHERE codigo = p_novo_pai) THEN RAISE EXCEPTION 'Posto % não existe.', p_novo_pai; END IF;
    IF p_novo_pai = p_posto OR EXISTS (SELECT 1 FROM public.rh_hier_descendentes(p_posto) d WHERE d.codigo = p_novo_pai) THEN
      RAISE EXCEPTION 'Não dá para pôr % abaixo de um posto que está abaixo dele.', p_posto;
    END IF;
  END IF;
  SELECT pai_codigo INTO v_antes FROM public."RH_POSTO_HIERARQUIA" WHERE posto_codigo = p_posto;
  INSERT INTO public."RH_POSTO_HIERARQUIA" (posto_codigo, pai_codigo, ordem, origem, alterado_por, alterado_em)
  VALUES (p_posto, p_novo_pai, 999, 'erp', v_nome, now())
  ON CONFLICT (posto_codigo) DO UPDATE SET pai_codigo = EXCLUDED.pai_codigo, origem = 'erp', alterado_por = v_nome, alterado_em = now();
  INSERT INTO public."RH_POSTO_HIERARQUIA_HIST" (posto_codigo, pai_antes, pai_depois, motivo, autor_nome)
  VALUES (p_posto, v_antes, p_novo_pai, btrim(p_motivo), v_nome);
END $$;
REVOKE ALL ON FUNCTION public.rh_hier_mover(text, text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_hier_mover(text, text, text) TO authenticated;

-- Tirar da hierarquia (volta para "fora da hierarquia").
CREATE OR REPLACE FUNCTION public.rh_hier_remover(p_posto text, p_motivo text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
  v_antes text;
  v_nome  text := (SELECT coalesce(display_name, email) FROM public.profiles WHERE id = auth.uid());
BEGIN
  IF NOT public.rh_hier_pode('alterar') THEN RAISE EXCEPTION 'Sem permissão para alterar a hierarquia.' USING ERRCODE = '42501'; END IF;
  IF btrim(coalesce(p_motivo, '')) = '' THEN RAISE EXCEPTION 'Informe o motivo da mudança.'; END IF;
  IF EXISTS (SELECT 1 FROM public."RH_POSTO_HIERARQUIA" WHERE pai_codigo = p_posto) THEN
    RAISE EXCEPTION 'O posto % tem postos abaixo dele — mova-os antes.', p_posto;
  END IF;
  SELECT pai_codigo INTO v_antes FROM public."RH_POSTO_HIERARQUIA" WHERE posto_codigo = p_posto;
  DELETE FROM public."RH_POSTO_HIERARQUIA" WHERE posto_codigo = p_posto;
  INSERT INTO public."RH_POSTO_HIERARQUIA_HIST" (posto_codigo, pai_antes, pai_depois, motivo, autor_nome)
  VALUES (p_posto, v_antes, NULL, '[removido da hierarquia] ' || btrim(p_motivo), v_nome);
END $$;
REVOKE ALL ON FUNCTION public.rh_hier_remover(text, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.rh_hier_remover(text, text) TO authenticated;

-- ── 9) Postos novos criados na Senior (espelho.BiPostos) ─────────────────
